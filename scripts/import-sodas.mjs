#!/usr/bin/env node
// Sodabench catalog import.
//
//   node scripts/import-sodas.mjs build-data <catalog.json> <walmart-items.jsonl>...
//     Rebuild scripts/data/sodas.json from a Walmart scrape. Skips excluded entries and variety packs.
//
//   node scripts/import-sodas.mjs sql
//     Write migrations/0012_soda_catalog.sql from scripts/data/sodas.json.
//
//   node scripts/import-sodas.mjs upload --local|--remote [--images-dir DIR] [--skip-missing] [--persist-to DIR]
//     Put each soda image into the lunchbench-images R2 bucket under its deterministic key.
//     Reads <walmart_item_id>.(jpeg|jpg|png) from --images-dir when present, else downloads image_url.
//     --skip-missing skips sodas with no local file instead of downloading.
//     --remote writes to the production bucket. It is a deploy step; run it deliberately.
//
// Image keys are images/<uuidv5(walmart url)>.<ext>, so the migration and the uploads agree.

import { createHash } from 'node:crypto'
import { existsSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { dirname, extname, join, resolve } from 'node:path'
import { spawnSync } from 'node:child_process'
import { fileURLToPath } from 'node:url'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const DATA_FILE = join(ROOT, 'scripts', 'data', 'sodas.json')
const MIGRATION_FILE = join(ROOT, 'migrations', '0012_soda_catalog.sql')
const BUCKET = 'lunchbench-images'
// RFC 4122 URL namespace.
const URL_NAMESPACE = '6ba7b811-9dad-11d1-80b4-00c04fd430c8'
const CONTENT_TYPES = { jpg: 'image/jpeg', png: 'image/png', webp: 'image/webp' }

export function uuidv5(name, namespace = URL_NAMESPACE) {
  const ns = Buffer.from(namespace.replace(/-/g, ''), 'hex')
  const hash = createHash('sha1').update(Buffer.concat([ns, Buffer.from(name, 'utf8')])).digest()
  hash[6] = (hash[6] & 0x0f) | 0x50
  hash[8] = (hash[8] & 0x3f) | 0x80
  const hex = hash.subarray(0, 16).toString('hex')
  return `${hex.slice(0, 8)}-${hex.slice(8, 12)}-${hex.slice(12, 16)}-${hex.slice(16, 20)}-${hex.slice(20, 32)}`
}

export function imageKey(soda) {
  return `images/${uuidv5(`https://www.walmart.com/ip/${soda.walmart_item_id}`)}.${soda.image_ext}`
}

function normalizeExt(ext) {
  const clean = ext.replace(/^\./, '').toLowerCase()
  if (clean === 'jpeg' || clean === 'jpg') return 'jpg'
  if (clean === 'png' || clean === 'webp') return clean
  throw new Error(`Unsupported image extension: ${ext}`)
}

function readSodas() {
  return JSON.parse(readFileSync(DATA_FILE, 'utf8'))
}

function buildData(catalogPath, itemFiles) {
  if (!catalogPath || itemFiles.length === 0) {
    throw new Error('Usage: build-data <catalog.json> <walmart-items.jsonl>...')
  }
  const imageUrls = new Map()
  for (const file of itemFiles) {
    for (const line of readFileSync(file, 'utf8').split('\n')) {
      if (!line.trim()) continue
      const item = JSON.parse(line)
      if (item.image) imageUrls.set(String(item.usItemId), item.image)
    }
  }

  const catalog = JSON.parse(readFileSync(catalogPath, 'utf8'))
  const sodas = catalog
    .filter((entry) => !entry.exclude && !entry.is_variety_pack)
    .map((entry) => {
      const itemId = String(entry.image_file).split('/').pop().replace(/\.[^.]+$/, '')
      if (!entry.skus.some((sku) => String(sku.usItemId) === itemId)) {
        throw new Error(`Image ${itemId} is not a SKU of ${entry.brand} ${entry.flavor}`)
      }
      const imageUrl = imageUrls.get(itemId)
      if (!imageUrl) throw new Error(`No image URL for ${itemId}`)
      if (entry.type !== 'soda' && entry.type !== 'seltzer') {
        throw new Error(`Bad type for ${itemId}: ${entry.type}`)
      }
      return {
        walmart_item_id: itemId,
        brand: entry.brand,
        flavor: entry.flavor,
        type: entry.type,
        image_url: imageUrl,
        image_ext: normalizeExt(extname(entry.image_file)),
      }
    })
    .sort((a, b) => a.brand.localeCompare(b.brand) || a.flavor.localeCompare(b.flavor))

  writeFileSync(DATA_FILE, `${JSON.stringify(sodas, null, 2)}\n`)
  console.log(`Wrote ${sodas.length} sodas to ${DATA_FILE}`)
}

function sqlString(value) {
  return `'${String(value).replace(/'/g, "''")}'`
}

function writeSql() {
  const sodas = readSodas()
  const rows = sodas.map((soda) =>
    `  (${[soda.walmart_item_id, soda.brand, soda.flavor, soda.type, imageKey(soda)].map(sqlString).join(', ')})`
  )
  const sql = [
    '-- Sodabench catalog: canned sodas and seltzers stocked at Walmart Branford CT #2232.',
    '-- Generated by `node scripts/import-sodas.mjs sql` from scripts/data/sodas.json. Do not edit by hand.',
    '-- Data only. Safe to re-run: rows are keyed by walmart_item_id.',
    '-- Upload the matching images with `node scripts/import-sodas.mjs upload`.',
    'INSERT OR IGNORE INTO sodas (walmart_item_id, brand, flavor, type, image_key) VALUES',
    `${rows.join(',\n')};`,
    '',
  ].join('\n')
  writeFileSync(MIGRATION_FILE, sql)
  console.log(`Wrote ${sodas.length} rows to ${MIGRATION_FILE}`)
}

function wranglerCommand() {
  const local = join(ROOT, 'worker', 'node_modules', '.bin', 'wrangler')
  return existsSync(local) ? [local] : ['npx', 'wrangler']
}

function findLocalImage(dir, itemId) {
  for (const ext of ['jpeg', 'jpg', 'png', 'webp']) {
    const file = join(dir, `${itemId}.${ext}`)
    if (existsSync(file)) return { file, contentType: CONTENT_TYPES[normalizeExt(ext)] }
  }
  return null
}

async function download(url, dest) {
  const res = await fetch(url)
  if (!res.ok) throw new Error(`Download failed ${res.status}: ${url}`)
  writeFileSync(dest, Buffer.from(await res.arrayBuffer()))
  const type = res.headers.get('content-type')?.split(';')[0]
  return Object.values(CONTENT_TYPES).includes(type) ? type : null
}

async function upload(args) {
  const local = args.includes('--local')
  const remote = args.includes('--remote')
  if (local === remote) throw new Error('upload needs exactly one of --local or --remote')
  const imagesDir = valueOf(args, '--images-dir')
  const persistTo = valueOf(args, '--persist-to')
  const skipMissing = args.includes('--skip-missing')
  const [cmd, ...cmdArgs] = wranglerCommand()
  const tmp = mkdtempSync(join(tmpdir(), 'sodabench-images-'))
  let uploaded = 0

  try {
    for (const soda of readSodas()) {
      const key = imageKey(soda)
      let source = imagesDir ? findLocalImage(resolve(imagesDir), soda.walmart_item_id) : null
      if (!source) {
        if (skipMissing) continue
        const file = join(tmp, `${soda.walmart_item_id}.${soda.image_ext}`)
        const type = await download(soda.image_url, file)
        source = { file, contentType: type ?? CONTENT_TYPES[soda.image_ext] }
      }

      const putArgs = [
        ...cmdArgs, 'r2', 'object', 'put', `${BUCKET}/${key}`,
        '--file', source.file,
        '--content-type', source.contentType,
      ]
      if (local) putArgs.push('--local')
      if (local && persistTo) putArgs.push('--persist-to', resolve(persistTo))
      const result = spawnSync(cmd, putArgs, { cwd: join(ROOT, 'worker'), stdio: ['ignore', 'pipe', 'pipe'] })
      if (result.status !== 0) {
        throw new Error(`wrangler put failed for ${key}: ${result.stderr.toString()}`)
      }
      uploaded += 1
      console.log(`${key} <- ${soda.brand} ${soda.flavor}`)
    }
  } finally {
    rmSync(tmp, { recursive: true, force: true })
  }
  console.log(`Uploaded ${uploaded} images to ${local ? 'local' : 'remote'} ${BUCKET}`)
}

function valueOf(args, flag) {
  const index = args.indexOf(flag)
  return index >= 0 ? args[index + 1] : undefined
}

async function main() {
  const [command, ...args] = process.argv.slice(2)
  if (command === 'build-data') return buildData(args[0], args.slice(1))
  if (command === 'sql') return writeSql()
  if (command === 'upload') return upload(args)
  if (command === 'keys') {
    for (const soda of readSodas()) console.log(`${soda.walmart_item_id}\t${imageKey(soda)}\t${soda.brand} ${soda.flavor}`)
    return
  }
  console.error('Usage: import-sodas.mjs build-data|sql|upload|keys (see header comment)')
  process.exit(1)
}

// Run only as a CLI, so tests can import the key helpers.
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main().catch((error) => {
    console.error(error.message)
    process.exit(1)
  })
}
